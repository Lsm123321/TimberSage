const applyTheme = () => {
  const themeToken = state.theme === 'light' ? 'v2-light' : 'v2'
  document.documentElement.setAttribute('data-theme', themeToken)
}

const applyButtonStyle = () => {
  document.documentElement.setAttribute('data-button-style', state.buttonStyle)
}

const applyLanguage = () => {
  const langToken = state.language === 'en' ? 'en' : 'zh-CN'
  document.documentElement.setAttribute('lang', langToken)
}

const initializePreferences = () => {
  if (initialized) return
  initialized = true
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw) {
      const parsed = JSON.parse(raw)
      if (parsed.language === 'zh' || parsed.language === 'en') {
        state.language = parsed.language
      }
      if (parsed.theme === 'dark' || parsed.theme === 'light') {
        state.theme = parsed.theme
      }
      if (['rounded', 'glass', 'neon'].includes(parsed.buttonStyle)) {
        state.buttonStyle = parsed.buttonStyle
      }
    }
  } catch (error) {
    console.warn('[UiPreferences] 读取界面偏好失败', error)
  }
  applyTheme()
  applyButtonStyle()
  applyLanguage()
}

const persistPreferences = () => {
  localStorage.setItem(STORAGE_KEY, JSON.stringify({
    language: state.language,
    theme: state.theme,
    buttonStyle: state.buttonStyle
  }))
}

const toggleLanguage = () => {
  state.language = state.language === 'zh' ? 'en' : 'zh'
  applyLanguage()
  persistPreferences()
}

const toggleTheme = () => {
  state.theme = state.theme === 'dark' ? 'light' : 'dark'
  applyTheme()
  persistPreferences()
}

const cycleButtonStyle = () => {
  const styles = ['rounded', 'glass', 'neon']
  const currentIndex = styles.indexOf(state.buttonStyle)
  const nextIndex = (currentIndex + 1) % styles.length
  state.buttonStyle = styles[nextIndex]
  applyButtonStyle()
  persistPreferences()
}

// 按当前语言取文案，缺 key 时原样返回 key 方便排查
const t = (key) => {
  const pack = messages[state.language] || messages.zh
  return pack[key] || key
}

/**
 * 全局 UI 偏好：语言（zh/en）、主题（dark/light）、按钮风格。
 * 中英文文案全在文件里（上面的大对象），改动后写 localStorage。
 */
export const useUiPreferences = () => {
  return {
    language: computed(() => state.language),
    theme: computed(() => state.theme),
    buttonStyle: computed(() => state.buttonStyle),
    initializePreferences,
    toggleLanguage,
    toggleTheme,
    cycleButtonStyle,
    t
  }
}
